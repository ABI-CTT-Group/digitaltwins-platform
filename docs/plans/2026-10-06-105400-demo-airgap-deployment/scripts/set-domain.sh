#!/usr/bin/env bash
# set-domain.sh — switch this install bundle between the shipped localhost
# config and a domain (https) config, for DEPLOYMENT-DOMAIN.md step 3.
#
#   bash set-domain.sh your.domain.example     # configure for https://your.domain.example
#   bash set-domain.sh --localhost             # back to the shipped localhost config
#   bash set-domain.sh --show                  # print the current setting
#
# Only data/env changes. The original localhost version is kept as
# data/env.localhost and every domain switch is generated from it, so it is safe
# to re-run (e.g. to correct a typo). data/secrets.env is never touched.
# Must be run BEFORE the platform install (DEPLOYMENT-DOMAIN.md step 6): the
# domain is fixed into the Keycloak realm on first start.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ENV="$HERE/data/env"
ORIG="$HERE/data/env.localhost"

[ -f "$ENV" ] || { echo "ERROR: $ENV not found — run this from the install_src folder."; exit 1; }
[ -f "$ORIG" ] || cp -p "$ENV" "$ORIG"     # first run: keep the shipped localhost config

show() { grep -E '^export (PLATFORM_PROTOCOL|PLATFORM_DOMAIN|KC_HOSTNAME_STRICT|KC_HOSTNAME_STRICT_HTTPS|PLATFORM_ADMIN_EMAIL)=' "$ENV"; }

case "${1:-}" in
  ""|-h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  --show) show; exit 0 ;;
  --localhost)
    cp -p "$ORIG" "$ENV"
    echo "Switched back to the localhost config:"; show; exit 0 ;;
esac

DOMAIN="$1"
# a plain host name: letters/digits/hyphens/dots, at least one dot, no scheme or path
if ! [[ "$DOMAIN" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)+$ ]]; then
  echo "ERROR: '$DOMAIN' doesn't look like a domain name."
  echo "       Give just the name, e.g.  digitaltwins.example.ac.nz  (no https://, no /path)."
  exit 1
fi

sed -e "s|^export PLATFORM_PROTOCOL=.*|export PLATFORM_PROTOCOL=https|" \
    -e "s|^export PLATFORM_DOMAIN=.*|export PLATFORM_DOMAIN=$DOMAIN|" \
    -e "s|^export KC_HOSTNAME_STRICT=.*|export KC_HOSTNAME_STRICT=true|" \
    -e "s|^export KC_HOSTNAME_STRICT_HTTPS=.*|export KC_HOSTNAME_STRICT_HTTPS=true|" \
    -e "s|^export PLATFORM_ADMIN_EMAIL=.*|export PLATFORM_ADMIN_EMAIL=admin@$DOMAIN|" \
    -e "s|^# demo deployment — http/localhost.*|# demo deployment — https://$DOMAIN (generated by set-domain.sh from env.localhost)|" \
    "$ORIG" > "$ENV.tmp"
mv "$ENV.tmp" "$ENV"

echo "Configured for https://$DOMAIN:"
show
echo

# --- advisory checks (don't block; just tell the operator what's still missing) ---
ok=true
if ip=$(getent hosts "$DOMAIN" | awk '{print $1; exit}') && [ -n "$ip" ]; then
  echo "✓ DNS: $DOMAIN -> $ip"
  hostname -I 2>/dev/null | tr ' ' '\n' | grep -qxF "$ip" \
    || echo "  (note: $ip is not one of this server's addresses — fine if it's a gateway/NAT address; otherwise check with IT)"
else
  echo "✗ DNS: $DOMAIN does not resolve yet — ask IT for the DNS record."; ok=false
fi

CERT="$HERE/data/fullchain.pem" KEY="$HERE/data/privkey.pem"
if [ -f "$CERT" ] && [ -f "$KEY" ]; then
  if openssl x509 -noout -checkhost "$DOMAIN" -in "$CERT" 2>/dev/null | grep -q 'does match'; then
    echo "✓ Certificate covers $DOMAIN, expires $(openssl x509 -noout -enddate -in "$CERT" | cut -d= -f2)"
  else
    echo "✗ Certificate in data/fullchain.pem is NOT for $DOMAIN — replace it (step 4)."; ok=false
  fi
else
  echo "… Certificate not added yet — do step 4 next."; ok=false
fi

echo
$ok && echo "Ready for step 5." || echo "Fix the ✗/… items above before step 6 (the platform install)."
